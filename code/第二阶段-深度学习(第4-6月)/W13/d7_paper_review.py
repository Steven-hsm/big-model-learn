    print("  引用: 100,000+ (截至2025)")
    print()

    # ----------------------------------------------------------
    print_separator("1. 论文解决的核心问题")
    # ----------------------------------------------------------
    print()
    print("2017年之前的序列建模问题:")
    print()
    print("  RNN/LSTM:")
    print("    - 顺序计算: 无法并行，训练慢")
    print("    - 长距离依赖: 梯度消失/爆炸")
    print("    - 固定大小隐藏状态: 信息瓶颈")
    print()
    print("  CNN (如 ByteNet, ConvS2S):")
    print("    - 可以并行，但需要多层才能捕捉长距离关系")
    print("    - O(N) 层才能连接所有位置")
    print()
    print("  注意力机制 (Bahdanau, Luong):")
    print("    - 已用于 RNN 之上改善长距离依赖")
    print("    - 但仍然是附加组件，不是核心架构")
    print()
    print("  论文的核心洞察:")
    print("    '我们不需要 RNN，仅靠注意力机制就足够了!'")
    print()

    # ----------------------------------------------------------
    print_separator("2. 核心创新")
    # ----------------------------------------------------------
    print()
    print("创新 1: Scaled Dot-Product Attention")
    print("  Attention(Q,K,V) = softmax(QK^T / sqrt(d_k)) @ V")
    print("  - 去掉了 RNN 的顺序依赖")
    print("  - O(1) 步连接任意两个位置")
    print()
    print("创新 2: Multi-Head Attention")
    print("  - 多个头并行关注不同方面")
    print("  - 每个头学习不同的注意力模式")
    print("  - head_i = Attention(QW_q_i, KW_k_i, VW_v_i)")
    print("  - output = Concat(head_1,...,head_h) @ W_o")
    print()
    print("创新 3: 完全基于注意力的编码器-解码器")
    print("  Encoder: 堆叠 N 个自注意力层")
    print("  Decoder: 堆叠 N 个带掩码的自注意力 + 交叉注意力层")
    print("  - 没有任何 RNN 或 CNN")
    print("  - 高度并行化")
    print()
    print("创新 4: Positional Encoding")
    print("  - 用 sin/cos 函数编码位置信息")
    print("  - 不需要学习，可以外推到更长序列")
    print()
    print("创新 5: 三种注意力角色的区分")
    print("  - 编码器自注意力: 源序列内部关系")
    print("  - 解码器掩码自注意力: 目标序列内部关系 (因果)")
    print("  - 编码器-解码器注意力: 源和目标之间的对齐")
    print()

    # ----------------------------------------------------------
    print_separator("3. 架构细节")
    # ----------------------------------------------------------
    print()
    print("原始 Transformer (base):")
    print("  d_model = 512")
    print("  num_heads = 8")
    print("  d_ff = 2048")
    print("  num_layers = 6 (encoder) + 6 (decoder)")
    print("  参数量: ~65M")
    print()
    print("原始 Transformer (big):")
    print("  d_model = 1024")
    print("  num_heads = 16")
    print("  d_ff = 4096")
    print("  num_layers = 6 + 6")
    print("  参数量: ~213M")
    print()
    print("训练细节:")
