    print("  学习率: warmup + inverse sqrt decay")
    print("  lr = d_model^(-0.5) * min(step^(-0.5), step * warmup^(-1.5))")
    print("  warmup_steps = 4000")
    print("  正则化: Dropout(0.1) + Label Smoothing(0.1)")
    print("  训练数据: WMT 2014 English-German (450万句对)")
    print("  训练时间: 8 P100 GPUs, 3.5 天 (base)")
