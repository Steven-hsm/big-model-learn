    print(f"  {'Transformer (base)':>20} | {'27.30':>15} | {'低':>12} | {'极好':>10}")
    print(f"  {'Transformer (big)':>20} | {'28.40':>15} | {'中等':>12} | {'极好':>10}")
    print()
    print("关键改进:")
    print("  1. BLEU 分数显著提升")
    print("  2. 训练成本大幅降低 (更少的 GPU 时间)")
    print("  3. 完全可并行化")
    print()

    # ----------------------------------------------------------
    print_separator("5. 论文的局限性")
    # ----------------------------------------------------------
    print()
    print("1. 计算复杂度:")
    print("   自注意力: O(n^2 * d)")
    print("   - 序列长度 n 增大时，计算量和内存平方增长")
    print("   - 长文档处理受限 (如书籍)")
    print()
    print("2. 位置编码:")
    print("   - sin/cos 编码是固定的，不是学习的")
    print("   - 外推到更长序列效果不好")
    print()
    print("3. 只验证了机器翻译任务:")
    print("   - 论文只在 WMT 翻译任务上做了实验")
    print("   - 其他 NLP 任务和 CV 领域的效果未知")
    print()
    print("4. 解码仍然串行:")
    print("   - 编码器可以并行，但解码器生成仍然需要自回归")
    print("   - 推理速度受限于序列长度")
    print()
    print("5. 缺乏归纳偏置 (inductive bias):")
    print("   - 不像 CNN 有局部性假设")
    print("   - 需要更多数据才能学好")
    print("   - 小数据集上可能不如 LSTM/CNN")
    print()

    # ----------------------------------------------------------
    print_separator("6. 现代改进方向")
    # ----------------------------------------------------------
    print()
    print("1. 高效注意力 (降低 O(n^2) 复杂度):")
