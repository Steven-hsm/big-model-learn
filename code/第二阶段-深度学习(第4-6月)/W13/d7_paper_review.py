    print(f"  {'ConvS2S':>20} | {'25.16':>15} | {'中等':>12} | {'较好':>10}")
    print(f"  {'GNMT+RL (RNN)':>20} | {'24.61':>15} | {'高':>12} | {'差':>10}")
